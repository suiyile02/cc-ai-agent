package com.ai.rag;

/**
 * 一次问答在"证据可用性"维度上的最终出口(检索**事后**算出的事实，不是事前猜测)。
 *
 * <p>取代 `RagMode` 的预判语义：`RagMode` 回答"这问题像哪一类"，本类型回答"这轮实际依据什么作答"。
 * 放在 rag 模块根包，因为它同时被 chat(编排)、context(装配选提示词)、system(审计落库) 消费。
 *
 * <p>只有三个出口是程序可判定的；"资料只覆盖了问题的一部分"需要理解语义，属提示词层对模型的期望，
 * 审计上仍归入 {@link #ANSWERED_FROM_KB}，不设第四个程序出口。
 */
public enum ChatOutcome {

    /** 语义路有过阈值命中且最终注入了资料：依据知识库作答 */
    ANSWERED_FROM_KB,

    /**
     * 正语义缓存命中：回答来自上一轮同样"有知识库依据"的作答。
     *
     * <p>取代旧的推断式不变式——从前靠 {@code rag_mode=KB 且 retrieval_executed=false} 反推缓存命中，
     * 而 P3-7 把缓存查询挪到检索之后（不再能跳过检索），该组合不再成立，故升为显式值。
     * 由编排层在命中分支赋值，{@link OutcomeResolver} 不产出它。
     */
    ANSWERED_FROM_CACHE,

    /** 严格知识库模式下无据可依：按固定口径友好拒答 */
    REFUSED_NO_EVIDENCE,

    /** 无知识库依据但允许自由作答（非严格模式），或本轮根本没执行检索（AGENT/非 RAG 会话） */
    ANSWERED_OPEN,

    /**
     * 【已被替代】决策时点不再产出本值（旧"工具轮跳过检索"已废除，见 {@link #NO_EVIDENCE_WITH_TOOLS}）。
     * 现为<b>事后出口</b>：收尾阶段发现本轮实际调用了工具，把统计口径升级为 TOOL_DATA——
     * 答案含工具返回的实时数据。提示词选择矩阵仍保留本分支作防御。
     */
    TOOL_DATA,

    /**
     * 知识库零命中但本会话注册了业务工具（严格模式）：不直接拒答，交给模型按
     * {@code prompts/tools-fallback.st} 裁决——落在某工具适用范围内则调工具作答，
     * 确认无工具可答才按固定口径拒答。
     *
     * <p>判定依据全部是确定性事实：检索已执行且未降级 + 语义路零命中 + 会话注册了工具。
     * 取代旧"词表猜工具轮→跳过检索"——词表按实体名词匹配会误判（"订单的报销制度是什么"），
     * 在严格模式下把知识库能答的问题错拒。
     */
    NO_EVIDENCE_WITH_TOOLS
}
